/*
 * Generates src/styles/palette.css — the CSS variables behind every Tailwind
 * colour scale (see tailwind.config.js).
 *
 *  - :root keeps Tailwind's stock values, so staff / admin screens look
 *    exactly as before.
 *  - html[data-audience='patient'] swaps in the patient palette (Pine,
 *    Lagoon, Leaf, Marigold, Rose, Dusk, Ink), built in OKLCH so each
 *    step is perceptually even.
 *
 * Run: node scripts/generate-palette.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import colors from 'tailwindcss/colors.js'

const here = path.dirname(fileURLToPath(import.meta.url))
const out = path.resolve(here, '../src/styles/palette.css')

const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]

function oklchToRgb(L, C, H) {
  const h = (H * Math.PI) / 180
  const a = C * Math.cos(h)
  const b = C * Math.sin(h)
  const l_ = L + 0.3963377774 * a + 0.2158037573 * b
  const m_ = L - 0.1055613458 * a - 0.0638541728 * b
  const s_ = L - 0.0894841775 * a - 1.291485548 * b
  const l = l_ ** 3
  const m = m_ ** 3
  const s = s_ ** 3
  const r = 4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s
  const g = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s
  const bl = -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s
  const f = (x) => {
    const c = Math.max(0, Math.min(1, x))
    return Math.round(255 * (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055))
  }
  return [f(r), f(g), f(bl)]
}

const LIGHTNESS = [0.975, 0.945, 0.895, 0.825, 0.735, 0.635, 0.545, 0.465, 0.395, 0.335, 0.25]
const CHROMA = [0.12, 0.25, 0.45, 0.7, 0.9, 1, 0.97, 0.88, 0.75, 0.62, 0.5]

function scale(hue, chroma, { lift = 0 } = {}) {
  return Object.fromEntries(
    STEPS.map((step, i) => [step, oklchToRgb(LIGHTNESS[i] + (i > 2 && i < 9 ? lift : 0), chroma * CHROMA[i], hue)])
  )
}

const ink = Object.fromEntries(
  STEPS.map((step, i) => [
    step,
    oklchToRgb(
      // 400–600 are used for secondary text; kept dark enough for 4.5:1 on white.
      [0.982, 0.958, 0.915, 0.855, 0.545, 0.49, 0.43, 0.375, 0.3, 0.235, 0.165][i],
      [0.004, 0.006, 0.009, 0.012, 0.016, 0.018, 0.018, 0.018, 0.016, 0.014, 0.012][i],
      170
    ),
  ])
)

const patient = {
  pine: scale(172, 0.12),
  lagoon: scale(218, 0.11),
  leaf: scale(150, 0.14),
  marigold: scale(68, 0.165, { lift: 0.05 }),
  rose: scale(12, 0.19),
  dusk: scale(285, 0.13),
  ink,
}

// Which Tailwind palette each patient family takes over.
const PATIENT_MAP = {
  primary: 'pine', blue: 'pine', teal: 'pine',
  sky: 'lagoon', cyan: 'lagoon',
  indigo: 'dusk', violet: 'dusk', purple: 'dusk',
  emerald: 'leaf', green: 'leaf',
  amber: 'marigold', orange: 'marigold', yellow: 'marigold',
  rose: 'rose', red: 'rose', pink: 'rose',
  slate: 'ink', gray: 'ink', zinc: 'ink', neutral: 'ink',
}

// Original custom primary scale (matches the previous tailwind.config.js).
const PRIMARY = {
  50: '#f0f7ff', 100: '#dcebff', 200: '#c2dcfd', 300: '#98c4fb', 400: '#64a7f8', 500: '#2f8cff',
  600: '#1f76e8', 700: '#175bb7', 800: '#154d99', 900: '#14407d', 950: '#0e2a52',
}

const hexToRgb = (hex) => {
  const v = hex.replace('#', '')
  return [0, 2, 4].map((i) => parseInt(v.slice(i, i + 2), 16))
}
const triple = (rgb) => rgb.join(' ')

const lines = []
lines.push('/* AUTO-GENERATED by scripts/generate-palette.mjs — do not edit by hand. */')
lines.push(':root {')
for (const name of Object.keys(PATIENT_MAP)) {
  const source = name === 'primary' ? PRIMARY : colors[name]
  for (const step of STEPS) {
    lines.push(`  --c-${name}-${step}: ${triple(hexToRgb(source[step]))};`)
  }
}
lines.push('}')
lines.push('')
lines.push("html[data-audience='patient'] {")
for (const [name, family] of Object.entries(PATIENT_MAP)) {
  for (const step of STEPS) {
    lines.push(`  --c-${name}-${step}: ${triple(patient[family][step])};`)
  }
}
lines.push('}')
lines.push('')

// In dark mode the same muted-text steps sit on near-black, so they need to be
// lighter, not darker, to stay readable (4.5:1 on the night surfaces).
const darkInk = {
  400: oklchToRgb(0.76, 0.014, 170),
  500: oklchToRgb(0.68, 0.016, 170),
}
lines.push("html.dark[data-audience='patient'] {")
for (const [name, family] of Object.entries(PATIENT_MAP)) {
  if (family !== 'ink') continue
  for (const [step, rgb] of Object.entries(darkInk)) {
    lines.push(`  --c-${name}-${step}: ${triple(rgb)};`)
  }
}
lines.push('}')
lines.push('')

fs.writeFileSync(out, lines.join('\n'))
console.log(`wrote ${path.relative(process.cwd(), out)}`)
